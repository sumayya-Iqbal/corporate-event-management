
# Import Python's datetime type.
# We use it to define date and time fields in our database models.
from datetime import datetime


# Import SQLAlchemy column types and database constraints.
from sqlalchemy import (
    String,          # Stores text with a defined maximum length.
    Integer,         # Stores whole numbers.
    Text,            # Stores longer text without a small fixed length.
    DateTime,        # Stores date and time values.
    ForeignKey,      # Connects a column to another table's column.
    UniqueConstraint,  # Prevents duplicate combinations of values.
    func             # Provides SQL database functions such as NOW().
)


# Import SQLAlchemy tools for defining database columns and relationships.
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Import Base from db.py.
# All our database model classes inherit from Base.
# This allows SQLAlchemy to recognize them as database tables.
from app.db import Base


# -------------------------
# USER MODEL
# -------------------------

# The User class represents the users table in PostgreSQL.
# It stores information about employees and administrators.
class User(Base):

    # Tell SQLAlchemy the exact database table name.
    __tablename__ = "users"

    # Primary key:
    # Every user gets a unique ID generated by the database.
    # index=True helps the database find records using this column efficiently.
    id: Mapped[int] = mapped_column(primary_key=True, index=True)

    # Store the user's name.
    # String(100) allows up to 100 characters.
    # nullable=False means this field cannot be empty in the database.
    name: Mapped[str] = mapped_column(String(100), nullable=False)

    # Store the user's email address.
    # unique=True prevents two users from registering with the same email.
    # index=True helps with searches by email.
    email: Mapped[str] = mapped_column(
        String(150), unique=True, nullable=False, index=True
    )

    # Store the hashed password, never the original plain-text password.
    # String(255) provides enough space for the password hash.
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)

    # Store the user's role.
    # New users receive the "employee" role by default.
    # Admin accounts can be assigned the "admin" role.
    role: Mapped[str] = mapped_column(
        String(20), default="employee", nullable=False
    )

    # Define a relationship between User and Registration.
    #
    # One user can have multiple event registrations.
    # back_populates="user" connects this relationship to
    # the user relationship inside the Registration model.
    #
    # This is an ORM relationship, not an additional database column.
    registrations: Mapped[list["Registration"]] = relationship(
        back_populates="user"
    )


# -------------------------
# EVENT MODEL
# -------------------------

# The Event class represents the events table.
# It stores information about corporate events, workshops,
# product launches, training sessions, and conferences.
class Event(Base):

    # Tell SQLAlchemy the exact database table name.
    __tablename__ = "events"

    # Primary key: unique ID for every event.
    id: Mapped[int] = mapped_column(primary_key=True, index=True)

    # Store the event title.
    # Example: "AI and Data Science Workshop".
    title: Mapped[str] = mapped_column(String(150), nullable=False)

    # Store an optional event description.
    # str | None means this value can be text or None.
    # nullable=True allows the database column to remain empty.
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Store the event's date and time.
    # timezone=True allows timezone-aware date and time values.
    # nullable=False means every event must have an event date.
    event_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )

    # Store the event's location.
    # Example: "Conference Hall, Karachi".
    location: Mapped[str] = mapped_column(String(200), nullable=False)

    # Store the maximum number of people allowed to register.
    # Integer means this field stores a whole number.
    capacity: Mapped[int] = mapped_column(Integer, nullable=False)

    # Store when the event record was created.
    #
    # server_default=func.now() tells the database to automatically
    # insert the current date and time when a new event is created.
    # The application does not need to provide this value manually.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Define the relationship between Event and Registration.
    #
    # One event can have multiple registrations from different users.
    # back_populates="event" connects this relationship to
    # the event relationship inside the Registration model.
    registrations: Mapped[list["Registration"]] = relationship(
        back_populates="event"
    )


# -------------------------
# REGISTRATION MODEL
# -------------------------

# The Registration class represents the registrations table.
#
# This table connects users with events.
# It is called a junction table because it connects two other tables.
#
# Example:
# User 1 registers for Event 3.
# The registrations table stores user_id=1 and event_id=3.
class Registration(Base):

    # Tell SQLAlchemy the exact database table name.
    __tablename__ = "registrations"

    # Define a database-level constraint.
    # The combination of user_id and event_id must be unique.
    #
    # This prevents the same user from registering for the same event twice.
    #
    # Why is this important?
    # Even if application-level duplicate checking fails,
    # the database still protects against duplicate registrations.
    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "event_id",
            name="unique_user_event_registration"
        ),
    )

    # Primary key: unique ID for each registration.
    id: Mapped[int] = mapped_column(primary_key=True, index=True)

    # Foreign key connecting this registration to a user.
    #
    # ForeignKey("users.id") means this value must refer to
    # an existing ID in the users table.
    #
    # ondelete="CASCADE" tells the database to delete registrations
    # when their related user is deleted.
    # nullable=False means every registration must have a user.
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False
    )

    # Foreign key connecting this registration to an event.
    #
    # ForeignKey("events.id") means this value must refer to
    # an existing ID in the events table.
    #
    # ondelete="CASCADE" tells the database to delete registrations
    # when their related event is deleted.
    # nullable=False means every registration must have an event.
    event_id: Mapped[int] = mapped_column(
        ForeignKey("events.id", ondelete="CASCADE"),
        nullable=False
    )

    # Store the date and time when the registration was created.
    # The database automatically supplies the current time.
    registered_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Define the relationship back to the User model.
    # This allows us to access the user associated with a registration.
    #
    # For example: registration.user
    user: Mapped["User"] = relationship(back_populates="registrations")

    # Define the relationship back to the Event model.
    # This allows us to access the event associated with a registration.
    #
    # For example: registration.event
    event: Mapped["Event"] = relationship(back_populates="registrations")
